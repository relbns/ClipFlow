import AppKit
import CryptoKit

/// Every item and every type on a pasteboard, so a clip or the user's clipboard can be put back exactly.
struct PasteboardSnapshot: Codable, Equatable {
    var items: [[String: Data]]

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let defaultMaxBytes = 50 * 1024 * 1024

    var isEmpty: Bool { items.allSatisfy(\.isEmpty) }
    var byteCount: Int { items.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } } }

    static func capture(from pasteboard: NSPasteboard, maxBytes: Int = defaultMaxBytes) -> PasteboardSnapshot? {
        var total = 0
        var items: [[String: Data]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var entry: [String: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > maxBytes { return nil }
                entry[type.rawValue] = data
            }
            if !entry.isEmpty { items.append(entry) }
        }
        return PasteboardSnapshot(items: items)
    }

    static func text(_ string: String, transient: Bool) -> PasteboardSnapshot {
        var entry = [NSPasteboard.PasteboardType.string.rawValue: Data(string.utf8)]
        if transient { entry[transientType.rawValue] = Data() }
        return PasteboardSnapshot(items: [entry])
    }

    /// Returns the pasteboard's change count right after the write.
    @discardableResult
    func write(to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let objects: [NSPasteboardItem] = items.map { entry in
            let item = NSPasteboardItem()
            for (type, data) in entry {
                item.setData(data, forType: NSPasteboard.PasteboardType(type))
            }
            return item
        }
        if !objects.isEmpty {
            pasteboard.writeObjects(objects)
        }
        return pasteboard.changeCount
    }

    func contains(_ type: NSPasteboard.PasteboardType) -> Bool {
        items.contains { $0[type.rawValue] != nil }
    }

    func data(for type: NSPasteboard.PasteboardType) -> Data? {
        items.lazy.compactMap { $0[type.rawValue] }.first
    }

    var string: String? {
        data(for: .string).flatMap { String(data: $0, encoding: .utf8) }
    }

    /// Clipboard managers must not record these (password managers, one-time or generated data).
    var isPrivate: Bool {
        contains(Self.concealedType) || contains(Self.transientType) || contains(Self.autoGeneratedType)
    }

    var contentHash: String {
        var hasher = SHA256()
        for entry in items {
            for key in entry.keys.sorted() where !key.hasPrefix("dyn.") {
                hasher.update(data: Data(key.utf8))
                hasher.update(data: entry[key] ?? Data())
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    func encoded() throws -> Data {
        try PropertyListEncoder().encode(self)
    }

    static func decoded(from data: Data) throws -> PasteboardSnapshot {
        try PropertyListDecoder().decode(PasteboardSnapshot.self, from: data)
    }
}
